// Generate the website's checked-in documentation data without changing v0.0.1.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { updateArchivedDocuments } from '../content/velamq/0.0.2/updates.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const source = path.join(root, 'content/velamq/0.0.2/zh')
const output = path.join(root, 'src/velamqDocsV002.generated.ts')
const check = process.argv.includes('--check')
const archiveSource = fs.readFileSync(path.join(root, 'src/velamqDocs.ts'), 'utf8')
const archiveStart = archiveSource.indexOf('= {', archiveSource.indexOf('export const velamqDocs:'))
if (archiveStart < 0) throw new Error('Cannot locate the archived documentation catalog')
const archive = JSON.parse(archiveSource.slice(archiveStart + 2)).zh

const navigation = [
  ['版本与升级', ['release-notes', 'upgrade']],
  ['规则引擎与函数', ['rules', 'builtin-functions', 'template-functions', 'custom-functions']],
  ['离线消息', ['offline-redis', 'offline-mysql']],
  ['系统与监控', ['config-migration', 'monitoring']],
]

// Deliberately limited to the Markdown used by this manual. Reject unsupported
// tables/fences rather than silently dropping configuration examples.
function parseDocument(id) {
  const raw = fs.readFileSync(path.join(source, `${id}.md`), 'utf8')
  const lines = raw.split('\n')
  const title = lines.shift().replace(/^# /, '')
  const blocks = []
  const headings = []
  let index = 0
  while (index < lines.length) {
    const line = lines[index].trim()
    if (!line) { index++; continue }
    if (line.startsWith('```')) {
      const language = line.slice(3)
      const code = []
      index++
      while (index < lines.length && lines[index].trim() !== '```') code.push(lines[index++])
      if (index === lines.length) throw new Error(`Unclosed code fence: ${id}`)
      index++
      blocks.push({ type: 'code', language, code: code.join('\n') })
      continue
    }
    const heading = /^(#{2,4}) (.+)$/.exec(line)
    if (heading) {
      const value = { id: `${id}-section-${headings.length + 1}`, level: heading[1].length, text: heading[2] }
      headings.push(value)
      blocks.push({ type: 'heading', ...value })
      index++
      continue
    }
    if (line.startsWith('|')) {
      const rows = []
      while (index < lines.length && lines[index].trim().startsWith('|')) {
        rows.push(lines[index++].trim().slice(1, -1).split('|').map(cell => cell.trim()))
      }
      const headers = rows.shift()
      const divider = rows.shift()
      if (!divider?.every(cell => /^:?-+:?$/.test(cell)) || rows.some(row => row.length !== headers.length)) {
        throw new Error(`Invalid Markdown table: ${id}`)
      }
      blocks.push({ type: 'table', headers, rows })
      continue
    }
    const ordered = /^\d+\. /.test(line)
    const list = ordered ? /^\d+\. (.+)$/ : /^- (.+)$/
    if (list.test(line)) {
      const items = []
      while (index < lines.length && list.test(lines[index].trim())) items.push(list.exec(lines[index++].trim())[1])
      blocks.push({ type: 'list', ordered, items })
      continue
    }
    const paragraph = [line]
    index++
    while (index < lines.length && lines[index].trim()) {
      if (/^(#|```|\||- |\d+\. )/.test(lines[index])) break
      paragraph.push(lines[index++].trim())
    }
    blocks.push({ type: 'paragraph', text: paragraph.join(' ') })
  }
  const introduction = blocks.find(block => block.type === 'paragraph')
  return { id, title, summary: introduction?.text ?? '',
    sourcePath: `content/velamq/0.0.2/zh/${id}.md`, headings,
    // The website already renders summary under the title.
    blocks: blocks.filter(block => block !== introduction) }
}

const additions = Object.fromEntries(navigation.flatMap(([, ids]) => ids).map(id => [id, parseDocument(id)]))
const documents = { ...updateArchivedDocuments(structuredClone(archive.documents), additions), ...additions }
const newGroups = navigation.map(([title, ids]) => ({ title,
  entries: ids.map(id => ({ type: 'doc', id, label: documents[id].title, depth: 0 })),
}))
const inheritedGroups = structuredClone(archive.groups)
for (const group of inheritedGroups) {
  for (const entry of group.entries) {
    if (entry.type === 'doc') entry.label = documents[entry.id].title
  }
}
const groups = [newGroups[0], ...inheritedGroups, ...newGroups.slice(1)]
const data = { documents, groups }
const generated = '// Generated by scripts/build-velamq-v002-docs.mjs. Edit content/velamq/0.0.2 instead.\n'
  + "import type { VelaMQDocDocument, VelaMQDocGroup } from './velamqDocs'\n\n"
  + 'export const velamqDocsV002Data: { documents: Record<string, VelaMQDocDocument>; groups: VelaMQDocGroup[] } = '
  + JSON.stringify(data, null, 2) + '\n'
if (check) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== generated) {
    throw new Error('Documentation data is stale. Run npm run docs:generate.')
  }
} else {
  fs.writeFileSync(output, generated)
}
console.log(`${check ? 'Verified' : 'Generated'} ${Object.keys(documents).length} documents (including all ${Object.keys(archive.documents).length} archived topics)`)
